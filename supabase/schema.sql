-- ---- vídeos ----------------------------------------------------------------
-- Duas naturezas na mesma tabela, separadas por `tipo`:
--   'video'       arquivo nosso, no bucket. `path` preenchido.
--   'video-link'  ponteiro pro YouTube/Instagram/Drive. `path` nulo, e não
--                 ocupa NADA do armazenamento — que é o motivo de existir.
-- Vídeo é o item capaz de estourar o 1 GB do plano free sozinho, então o
-- caminho do link é o preferido e o painel oferece os dois lado a lado.

create table if not exists public.videos (
  id         uuid primary key default gen_random_uuid(),
  imovel_id  uuid not null references public.imoveis (id) on delete cascade,
  tipo       text not null default 'video' check (tipo in ('video', 'video-link')),
  path       text,             -- só em tipo 'video'
  url        text not null,    -- URL pública do arquivo, ou o link colado
  ordem      smallint not null default 0,
  legenda    text,
  criado_em  timestamptz not null default now(),
  -- Arquivo sem caminho no bucket vira lixo impossível de apagar depois.
  constraint videos_path_coerente check (
    (tipo = 'video' and path is not null) or (tipo = 'video-link' and path is null)
  )
);

create index if not exists videos_imovel_idx on public.videos (imovel_id, ordem);


