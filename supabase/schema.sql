  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'imoveis' and public.e_equipe());

create policy "equipe troca fotos"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'imoveis' and public.e_equipe());

create policy "equipe apaga fotos"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'imoveis' and public.e_equipe());


-- ============================================================================
-- 9. RPC — o que o site anônimo pode chamar
-- ============================================================================

-- ---- registrar_lead -------------------------------------------------------
-- Porta única de entrada de lead. SECURITY DEFINER porque anon não tem
-- permissão de INSERT na tabela. Assim o visitante grava um lead sem nunca
-- poder ler, editar ou apagar a base de leads.
create or replace function public.registrar_lead(
  p_nome       text,
  p_telefone   text,
  p_mensagem   text default null,
  p_email      text default null,
  p_imovel_id  uuid default null,
  p_origem     text default 'site'
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  -- Validação mínima. O resto de qualidade de dado é problema do corretor.
  if coalesce(trim(p_nome), '') = '' then
    raise exception 'Informe o nome.';
  end if;

  if length(regexp_replace(coalesce(p_telefone, ''), '\D', '', 'g')) < 10 then
    raise exception 'Informe um telefone com DDD.';
  end if;

  if p_origem not in ('site', 'whatsapp', 'instagram', 'telefone', 'indicacao', 'portal') then
    p_origem := 'site';
  end if;

  insert into public.leads (nome, telefone, email, mensagem, imovel_id, origem, proximo_contato)
  values (
    left(trim(p_nome), 120),
    regexp_replace(p_telefone, '\D', '', 'g'),
    nullif(trim(coalesce(p_email, '')), ''),
    left(coalesce(p_mensagem, ''), 2000),
    p_imovel_id,
    p_origem,
    current_date + 1          -- follow-up padrão: cobrar o corretor no dia seguinte
  )
  returning id into v_id;

  if coalesce(trim(p_mensagem), '') <> '' then
    insert into public.lead_interacoes
      (lead_id, tipo, direcao, autor, canal, conteudo, automatico)
    values
      (v_id, 'mensagem', 'entrada', 'lead', p_origem,
       left(trim(p_mensagem), 4000), false);
  end if;

  return v_id;
end;
$$;

grant execute on function public.registrar_lead(text, text, text, text, uuid, text) to anon, authenticated;

-- ---- buscar_imoveis -------------------------------------------------------
-- Usada pelo agente de IA. Devolve poucos campos, já formatados, pra caber no
-- contexto do modelo sem estourar token. O agente passa o perfil do lead e
-- recebe as opções reais da carteira, em vez de inventar imóvel.
create or replace function public.buscar_imoveis(
  p_finalidade text default null,
  p_tipo       text default null,
  p_bairro     text default null,
  p_preco_max  numeric default null,
  p_quartos_min smallint default null,
  p_limite     integer default 5
)
returns table (
  codigo    integer,
  titulo    text,
  tipo      text,
  bairro    text,
  cidade    text,
  preco     numeric,
  quartos   smallint,
  banheiros smallint,
  vagas     smallint,
  area_util numeric
)
language sql
stable
security invoker           -- respeita o RLS: só devolve o que está publicado
set search_path = public
as $$
  select i.codigo, i.titulo, i.tipo, i.bairro, i.cidade, i.preco,
         i.quartos, i.banheiros, i.vagas, i.area_util
  from public.imoveis i
  where i.status in ('disponivel', 'reservado')
    and (p_finalidade  is null or i.finalidade = p_finalidade)
    and (p_tipo        is null or i.tipo       = p_tipo)
    -- public.sem_acento e não unaccent(): esta função roda com
    -- `set search_path = public`, então o schema `extensions` (onde o unaccent
    -- mora) fica fora do caminho aqui dentro.
    -- ⚠️ Casa com BAIRRO **ou** CIDADE de propósito. O agente recebe texto
    -- livre ("tem apartamento em Fortaleza?") e não tem como saber se o que
    -- veio é bairro ou cidade — na prática ele manda a cidade em p_bairro
    -- com frequência. Comparando só com i.bairro, a busca voltava vazia e o
    -- bot respondia "não temos" para um cliente que tinha imóvel disponível.
    -- Visto no app publicado em 11/08/2026. Lead perdido é pior que
    -- resultado amplo demais: aqui o filtro é generoso por escolha.
    and (p_bairro      is null
         or public.sem_acento(i.bairro) ilike '%' || public.sem_acento(p_bairro) || '%'
         or public.sem_acento(i.cidade) ilike '%' || public.sem_acento(p_bairro) || '%')
    and (p_preco_max   is null or i.preco     <= p_preco_max)
    and (p_quartos_min is null or i.quartos   >= p_quartos_min)
  order by i.destaque desc, i.preco asc
  limit least(coalesce(p_limite, 5), 20);
$$;

grant execute on function public.buscar_imoveis(text, text, text, numeric, smallint, integer) to anon, authenticated;


-- ============================================================================
-- 10. VIEW do catálogo — o que o site lê
-- ----------------------------------------------------------------------------
-- Junta a capa e a contagem de fotos numa consulta só, pra listagem não
-- precisar de N+1. security_invoker faz a view respeitar o RLS de imoveis.
-- ============================================================================

create or replace view public.catalogo
with (security_invoker = true)
as
select
  i.id, i.codigo, i.titulo, i.finalidade, i.tipo, i.preco, i.condominio,
  i.quartos, i.suites, i.banheiros, i.vagas, i.area_util, i.comodidades,
  i.bairro, i.cidade, i.uf, i.destaque, i.status, i.criado_em,
  case when i.mostrar_endereco then i.lat else null end as lat,
  case when i.mostrar_endereco then i.lng else null end as lng,
  (select f.url from public.fotos f
    where f.imovel_id = i.id order by f.ordem, f.criado_em limit 1) as capa,
  (select count(*) from public.fotos f where f.imovel_id = i.id)    as total_fotos,
  -- O cartão do catálogo mostra um selo "com vídeo", então a contagem tem que
  -- vir junto: sem isso seria uma consulta por cartão.
  (select count(*) from public.videos v where v.imovel_id = i.id)   as total_videos
from public.imoveis i;

grant select on public.catalogo to anon, authenticated;


