-- ============================================================================
-- 7. RLS — a única coisa que separa o site do seu pai de um site vandalizado
-- ----------------------------------------------------------------------------
-- A chave anon fica EXPOSTA no JavaScript. Isso é normal e esperado no
-- Supabase. Quem protege os dados são as policies abaixo, não a chave.
-- Se você errar aqui, qualquer visitante deleta a carteira inteira.
-- ============================================================================

-- ⚠️ TODA tabela do public precisa estar nesta lista. Policy escrita numa
-- tabela SEM RLS ligado é simplesmente ignorada pelo Postgres — não dá erro,
-- não avisa, e a tabela fica aberta. Foi o que aconteceu com `videos`, que
-- tinha as duas policies e ficou de fora daqui.
alter table public.corretores enable row level security;
alter table public.imoveis    enable row level security;
alter table public.fotos      enable row level security;
alter table public.videos     enable row level security;
alter table public.leads      enable row level security;
alter table public.visitas    enable row level security;
alter table public.lead_interacoes enable row level security;
alter table public.configuracoes_ia enable row level security;

-- Helper. É SECURITY DEFINER de propósito: ele lê a tabela corretores
-- ignorando o RLS dela. Sem isso, a policy de corretores chamaria uma função
-- que lê corretores, que dispara a policy de novo = recursão infinita
-- (erro 42P17). Esse é o jeito canônico de resolver no Postgres.
create or replace function public.e_equipe()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.corretores c
    where c.id = auth.uid() and c.ativo
  );
$$;

revoke execute on function public.e_equipe() from public;
grant  execute on function public.e_equipe() to authenticated;

-- ---- corretores -----------------------------------------------------------
-- A equipe é pública de propósito: nome, CRECI e telefone do corretor são
-- informação que a imobiliária quer divulgar.
drop policy if exists "equipe visivel para todos"   on public.corretores;
drop policy if exists "corretor edita o proprio perfil" on public.corretores;

create policy "equipe visivel para todos"
  on public.corretores for select
  using (ativo);

create policy "corretor edita o proprio perfil"
  on public.corretores for update
  to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

-- ---- imóveis --------------------------------------------------------------
drop policy if exists "imoveis publicados sao visiveis" on public.imoveis;
drop policy if exists "equipe ve tudo"                  on public.imoveis;
drop policy if exists "equipe escreve imoveis"          on public.imoveis;

-- Visitante anônimo só enxerga o que está no ar. Rascunho, vendido e alugado
-- não vazam nem pela API REST.
create policy "imoveis publicados sao visiveis"
  on public.imoveis for select
  using (status in ('disponivel', 'reservado'));

create policy "equipe ve tudo"
  on public.imoveis for select
  to authenticated
  using (public.e_equipe());

create policy "equipe escreve imoveis"
  on public.imoveis for all
  to authenticated
  using (public.e_equipe())
  with check (public.e_equipe());

-- ---- fotos ----------------------------------------------------------------
drop policy if exists "fotos de imovel publicado" on public.fotos;
drop policy if exists "equipe escreve fotos"      on public.fotos;

create policy "fotos de imovel publicado"
  on public.fotos for select
  using (
    exists (
      select 1 from public.imoveis i
      where i.id = fotos.imovel_id
        and i.status in ('disponivel', 'reservado')
    )
  );

create policy "equipe escreve fotos"
  on public.fotos for all
  to authenticated
  using (public.e_equipe())
  with check (public.e_equipe());

-- ---- vídeos ---------------------------------------------------------------
-- Mesma regra das fotos: visível só enquanto o imóvel estiver publicado.
drop policy if exists "videos de imovel publicado" on public.videos;
drop policy if exists "equipe escreve videos"      on public.videos;

create policy "videos de imovel publicado"
  on public.videos for select
  using (
    exists (
      select 1 from public.imoveis i
      where i.id = videos.imovel_id
        and i.status in ('disponivel', 'reservado')
    )
  );

create policy "equipe escreve videos"
  on public.videos for all
  to authenticated
  using (public.e_equipe())
  with check (public.e_equipe());

-- ---- leads e visitas ------------------------------------------------------
-- Sem policy para anon = ninguém de fora lê nem escreve direto. O site grava
-- lead exclusivamente pela RPC registrar_lead() logo abaixo.
drop policy if exists "equipe gerencia leads"   on public.leads;
drop policy if exists "equipe gerencia visitas" on public.visitas;
drop policy if exists "equipe gerencia interacoes" on public.lead_interacoes;
drop policy if exists "equipe gerencia configuracao ia" on public.configuracoes_ia;

create policy "equipe gerencia leads"
  on public.leads for all
  to authenticated
  using (public.e_equipe())
  with check (public.e_equipe());

create policy "equipe gerencia visitas"
  on public.visitas for all
  to authenticated
  using (public.e_equipe())
  with check (public.e_equipe());

create policy "equipe gerencia interacoes"
  on public.lead_interacoes for all
  to authenticated
  using (public.e_equipe())
  with check (public.e_equipe());

create policy "equipe gerencia configuracao ia"
  on public.configuracoes_ia for all
  to authenticated
  using (public.e_equipe())
  with check (public.e_equipe());

grant select, insert, update, delete on public.lead_interacoes to authenticated;
grant select, insert, update, delete on public.configuracoes_ia to authenticated;
grant all on public.lead_interacoes to service_role;
grant all on public.configuracoes_ia to service_role;


